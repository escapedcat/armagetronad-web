// ******************************************************************************************
// *
// *	Create
// *
// ******************************************************************************************
//!
//!		@param	fileName	name of the image file to load
//!
// ******************************************************************************************

void rSurface::Create( char const * fileName )
{
#ifndef DEDICATED
    sr_LockSDL();

    // find path of image
    // tString s = tResourceManager::locateResource("", fileName);
    tString s = tDirectories::Data().GetReadPath( fileName );

    // Load image
#ifdef __EMSCRIPTEN__
    // Emscripten's SDL/SDL_image.h declares IMG_InvertAlpha() but nothing
    // implements it, so the call is an undefined symbol at link time. That same
    // header (SDL_image.h:88-89) says of it: "This function is now a no-op, and
    // only provided for backwards compatibility." So dropping the call should
    // change nothing. If that turns out to be wrong the symptom is unmistakable
    // and global: every texture renders with its alpha channel inverted.
#else
    IMG_InvertAlpha(true);
#endif
    Create( IMG_Load(s) );

    //if ( surface_ )
    //    std::cerr << "loaded surface " << fileName << "\n";

    sr_UnlockSDL();
#endif
}

// ******************************************************************************************
// *
// *	Create
// *
// ******************************************************************************************
//!
//!		@param	surface
//!
// ******************************************************************************************

void rSurface::Create( SDL_Surface * surface )
{
#ifndef DEDICATED
    // clear previous surface
    Clear();

    // take ownership
    surface_ = surface;

    // determine texture format
    if ( surface_ )
    {
        switch (surface_->format->BytesPerPixel){
        case 1:
            format_ = GL_LUMINANCE;
            break;

        case 2:
#ifdef __EMSCRIPTEN__
            // format_ is handed to glTexImage2D's *external format* argument
            // (see rISurfaceTexture::Upload), and GL_LUMINANCE8_ALPHA8 is a
            // sized *internal* format. Desktop GL tolerated the confusion;
            // WebGL 1 accepts only GL_ALPHA/GL_LUMINANCE/GL_LUMINANCE_ALPHA/
            // GL_RGB/GL_RGBA there and rejects anything else with
            // GL_INVALID_ENUM. Emscripten's glTexImage2D would also size the
            // pixel read from it wrongly: libwebgl.js's
            // colorChannelsInGlTextureFormat falls back to 1 byte per pixel for
            // an unrecognised enum, so it would hand WebGL a half-length
            // buffer. This branch is unreachable in the Emscripten build --
            // SDL's IMG_Load_RW always returns a 32-bit surface, so
            // BytesPerPixel is always 4 -- but it costs one line to be right.
            format_ = GL_LUMINANCE_ALPHA;
#else
            format_ = GL_LUMINANCE8_ALPHA8;
#endif
            break;

        case 3:
            format_ = GL_RGB;
            break;

        case 4:
            format_ = GL_RGBA;
            break;

        default:
            {
                // fallback: convert the texture into a known format.

                SDL_Surface *dummy =
                    SDL_CreateRGBSurface(SDL_SWSURFACE, 1, 1,
                                         32,
                                         0x0000FF, 0x00FF00,
                                         0xFF0000 ,0xFF000000);

                SDL_Surface *convtex =
                    SDL_ConvertSurface(surface_, dummy->format, SDL_SWSURFACE);

                SDL_FreeSurface(surface_);
                surface_ = convtex;
                SDL_FreeSurface(dummy);

                format_ = GL_RGBA;
            }
            break;
        }
    }
#endif
}

// ******************************************************************************************
// *
// *	CopyFrom
// *
// ******************************************************************************************
//!
//!		@param	other
//!
// ******************************************************************************************

void rSurface::CopyFrom( rSurface const & other )
{
#ifndef DEDICATED
    tASSERT( 0 == surface_ );
    tASSERT( other.surface_ );

    // copy surface
    surface_ = SDL_ConvertSurface(other.surface_, other.surface_->format, SDL_SWSURFACE);

    // copy flags
    format_ = other.format_;
#endif
}

