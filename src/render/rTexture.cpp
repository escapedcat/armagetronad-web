void rISurfaceTexture::OnUnload( void )
{
#ifndef DEDICATED
    if (tint_ > 0)
    {
        rDisplayList::ClearAll();

        // std::cerr << "unloading texture " << fileName << ':' << tint_ << "\n";
        glDeleteTextures(1,&tint_);
        tint_ = 0;
    }

    textureModeLast_=-100;
    rITexture::OnUnload();
#endif
}

